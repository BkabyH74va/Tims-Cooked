def dis(name, hexstr, base):
    data = bytes.fromhex("".join(hexstr.split()))
    md = Cs(CS_ARCH_ARM64, CS_MODE_ARM)
    md.detail = False
    print("=" * 70)
    print("%s  base=0x%x  size=0x%x" % (name, base, len(data)))
    print("=" * 70)
    for i in md.disasm(data, base):
        mark = ""
        if i.mnemonic in ("bl", "b") and i.op_str.startswith("#0x"):
            mark = "   ; <== CALL/BRANCH"
        print("%016x  %-9s %-34s%s" % (i.address, i.mnemonic, i.op_str, mark))

